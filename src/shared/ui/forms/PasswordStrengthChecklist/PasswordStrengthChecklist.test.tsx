import { screen, within } from "@testing-library/react";
import { expect, it } from "vitest";
import { renderWithProviders } from "../../../../test/render";
import { PasswordStrengthChecklist } from "./PasswordStrengthChecklist";
it("074 pílulas mostram cinco regras, anunciam estado e nunca expõem a senha", () => {
  const { rerender } = renderWithProviders(<PasswordStrengthChecklist password="" />);
  const list = screen.getByRole("list", { name: "Requisitos da senha" });
  expect(list).toHaveAttribute("aria-live", "polite");
  expect(list).toHaveAttribute("aria-atomic", "false");
  const items = () => within(list).getAllByRole("listitem");
  expect(items()).toHaveLength(5);
  items().forEach((item) => expect(item).toHaveTextContent("Falta:"));
  rerender(<PasswordStrengthChecklist password="Abcdef1!" />);
  items().forEach((item) => expect(item).toHaveTextContent("Atendido:"));
  expect(list).not.toHaveTextContent("Abcdef1!");
  rerender(<PasswordStrengthChecklist password={"A".repeat(129) + "á1 "} />);
  expect(items()[0]).toHaveTextContent("Falta: 8 caracteres ou mais");
  expect(items()[4]).toHaveTextContent("Falta: Um símbolo (! @ # ...)");
  expect(items()[2]).toHaveTextContent("Atendido: Letra minúscula");
});
