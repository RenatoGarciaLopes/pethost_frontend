import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = fileURLToPath(new URL("../", import.meta.url));
const backend = path.resolve(root, "../pethost_backend");
const titles = new Set();
async function discover(directory) {
  for (const item of await fs.readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, item.name);
    if (item.isDirectory()) await discover(file);
    else if (item.name.endsWith("EmailNotifier.cs") || item.name === "ModerationEmailAlerts.cs") {
      const source = await fs.readFile(file, "utf8");
      for (const match of source.matchAll(/"PetHost — ([^"\r\n]+)"/g)) {
        const title = match[1].replace(" ({alert.Issue})", "");
        if (title.includes("{")) throw new Error(`Título dinâmico não mapeado: ${title}`);
        titles.add(title);
      }
    }
  }
}
await discover(path.join(backend, "src/Modules"));
if (titles.size < 30) throw new Error("Catálogo incompleto de e-mails.");
const output = path.join(root, "public/brand/email-headings");
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const entries = [];
try {
  const page = await browser.newPage({ viewport: { width: 520, height: 400 }, deviceScaleFactor: 2 });
  await page.route("https://brand.pethost.invalid/caprasimo.woff2", (route) =>
    route.fulfill({
      path: path.join(root, "public/fonts/caprasimo-latin-400-normal.woff2"),
      contentType: "font/woff2",
      headers: { "access-control-allow-origin": "*" },
    }),
  );
  await page.setContent(
    "<style>@font-face{font-family:Caprasimo;src:url('https://brand.pethost.invalid/caprasimo.woff2')}body{margin:0;background:#FFFFFF}h1{box-sizing:border-box;width:340px;padding:3px 0 5px;margin:0;background:#FFFFFF;font:400 36px/1.25 Caprasimo;color:#1F1A17;overflow-wrap:break-word}</style><h1></h1>",
  );
  await page.evaluate(() => document.fonts.load("36px Caprasimo"));
  if (!(await page.evaluate(() => document.fonts.check("36px Caprasimo")))) throw new Error("Caprasimo não carregou.");
  for (const title of [...titles].sort()) {
    const image = `${createHash("sha256").update(title).digest("hex").slice(0, 16)}.png`;
    await page.locator("h1").evaluate((element, value) => {
      element.textContent = value.charAt(0).toLocaleUpperCase("pt-BR") + value.slice(1);
    }, title);
    await page.locator("h1").screenshot({ path: path.join(output, image), omitBackground: false });
    const size = await page.locator("h1").boundingBox();
    entries.push({ title, image, width: Math.round(size.width), height: Math.ceil(size.height) });
  }
} finally {
  await browser.close();
}
const lines = entries.map(
  ({ title, image, width, height }) =>
    `        [${JSON.stringify(title)}] = new("/brand/email-headings/${image}", ${width}, ${height}),`,
);
const code = `// <auto-generated />\n// Generated by pethost_frontend/scripts/generate-email-headings.mjs from production notifier subjects.\nnamespace PetHost.Shared.Infrastructure.Email;\n\ninternal static class EmailHeadingAssets\n{\n    internal static readonly IReadOnlyDictionary<string, EmailHeadingImage> Images = new Dictionary<string, EmailHeadingImage>(StringComparer.Ordinal)\n    {\n${lines.join("\n")}\n    };\n}\n\ninternal sealed record EmailHeadingImage(string Path, int Width, int Height);\n`;
await fs.writeFile(path.join(backend, "src/Shared/PetHost.Shared.Infrastructure/Email/EmailHeadingAssets.g.cs"), code);
await fs.writeFile(
  path.join(root, "src/test/fixtures/emailHeadingAssets.json"),
  JSON.stringify(entries, null, 2) + "\n",
);
const current = new Set(entries.map((entry) => entry.image));
for (const file of await fs.readdir(output)) {
  if (/^[a-f0-9]{16}\.png$/.test(file) && !current.has(file)) await fs.unlink(path.join(output, file));
}
console.log(`Generated ${entries.length} production email headings and backend catalog.`);
