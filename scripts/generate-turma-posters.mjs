import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import { format } from "prettier";

// Extract the real first frame, including transparency. Never depend on a network request for the initial dog.
const members = ["corgi", "golden", "pastor"];
const entries = await Promise.all(
  members.map(async (member) => {
    const poster = await sharp(`public/brand/turma/${member}.webp`, { pages: 1 })
      .resize({ width: 128 })
      .webp({ quality: 85, effort: 6 })
      .toBuffer();
    return `  ${member}: "data:image/webp;base64,${poster.toString("base64")}",`;
  }),
);
await writeFile(
  "src/shared/ui/brand/turmaPosters.ts",
  await format(
    `// Generated by npm run brand:turma-posters from the original animated WebPs.\n` +
      `/** Embedded real first frames for cold-cache loaders and reduced motion. */\n` +
      `export const turmaPosters = {\n${entries.join("\n")}\n} as const;\n`,
    { parser: "typescript" },
  ),
);
