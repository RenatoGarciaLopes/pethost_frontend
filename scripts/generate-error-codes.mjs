/**
 * Gera `src/shared/api/generated/errorCodes.ts` a partir do enum `ApiErrorCode` do OpenAPI (contrato 090).
 * Roda como hook do Orval (`orval.config.ts`), então `api:generate` e `api:check` cobrem o arquivo.
 * O catálogo de frases (`shared/api/errors/errorCopy.ts`) é tipado por este enum: código novo sem frase quebra o tsc.
 */
import { readFile, writeFile } from "node:fs/promises";

const spec = JSON.parse(await readFile("openapi/pethost.v1.json", "utf8"));
const codes = spec.components?.schemas?.ApiErrorCode?.enum;
if (!Array.isArray(codes) || codes.length === 0) {
  console.error("O OpenAPI não tem o enum components.schemas.ApiErrorCode.");
  process.exit(1);
}

const lines = [...codes].sort().map((code) => `  "${code}",`);
await writeFile(
  "src/shared/api/generated/errorCodes.ts",
  `/**\n * Generated by scripts/generate-error-codes.mjs\n * Do not edit manually.\n */\nexport const API_ERROR_CODES = [\n${lines.join("\n")}\n] as const;\n\nexport type ApiErrorCode = (typeof API_ERROR_CODES)[number];\n`,
);
